    private void atualizarTabela(){
        DefaultTableModel modelo = (DefaultTableModel) tblConsultaMecanicos.getModel();
        
        modelo.setRowCount(0);
        
        String sql = "SELECT * FROM mecanico "
                     + "ORDER BY id";
        
        try (Connection conex = Conexao.conectar();
             PreparedStatement stmt = conex.prepareStatement(sql);
             ResultSet resultado = stmt.executeQuery() ){
            
            while (resultado.next()){
                modelo.addRow(new Object[] {
                    resultado.getInt("id"),
                    resultado.getString("nome"),
                    resultado.getString("especialidade"),
                    resultado.getString("telefone"),
                    
                    resultado.getBoolean("ativo") ? "Sim" : "Não"
                });
            }
        } catch (SQLException erro){
            JOptionPane.showMessageDialog(
                        this,
                        "Erro ao atualizar tabela:\n" + erro.getMessage(),
                        "Erro no banco de dados",
                        JOptionPane.ERROR_MESSAGE);
        }
    }

