    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
         int linha = tblConsultaMecanicos.getSelectedRow();
         
         if (linha == -1){
             JOptionPane.showMessageDialog(this,"Selecione um cliente na tabela para alterar");
             return;
         }
         
         
         int id = Integer.parseInt(tblConsultaMecanicos.getValueAt(linha,0).toString());
         
         
         String nome = txtNome.getText().trim();
         String especialidade = txtEspecialidade.getText().trim();
         String telefone = txtTelefone.getText().trim();
         String dataAdmissao = txtDataAdm.getText().trim();
         
        
         if (nome.isEmpty() || especialidade.isEmpty() || telefone.isEmpty()) {
             JOptionPane.showMessageDialog(this, "Preecha os campos OBRIGATÓRIOS: Nome, Especialidade, Telefone");
             return;
         }
         
        
         
         int resposta = JOptionPane.showConfirmDialog(this, 
                         "Deseja alterar os dados do mecanico de ID "+id+"?" ,
                         "Confirmar Alteração",
                         JOptionPane.YES_NO_CANCEL_OPTION,
                         JOptionPane.QUESTION_MESSAGE);
         if (resposta != JOptionPane.YES_OPTION) {
             return;
         }
         
        
         
         String sql = """
                      UPDATE mecanico
                      SET nome = ?, especialidade = ?, telefone = ?
                      WHERE id = ?
                      """;
         
         try (Connection conex = Conexao.conectar();
              PreparedStatement stmt = conex.prepareStatement(sql)){
           
             stmt.setString(1,nome);
             stmt.setString(2, especialidade);
             stmt.setString(3, telefone);
             stmt.setInt(4, id);
             
            
             int registros = stmt.executeUpdate();
             if (registros > 0){
                 JOptionPane.showMessageDialog(this, "mecanico alterado com sucesso!");
                 atualizarTabela();
                 txtId.setText("");
                 txtNome.setText("");
                 txtEspecialidade.setText("");
                 txtTelefone.setText("");
                 
                 chbAtivo.setSelected(false);
                 txtNome.requestFocus();
             } else {
                 JOptionPane.showMessageDialog(this, "Mecanico não encontrado");
             }
         } catch (SQLException erro){
           JOptionPane.showConfirmDialog(this, "Erro ao alterar mecanico: " + erro.getMessage());
         }
    }//GEN-LAST:event_btnAlterarActionPerformed

