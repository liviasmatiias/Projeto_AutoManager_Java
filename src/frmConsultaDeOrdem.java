    private void btnLocalizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLocalizarActionPerformed
        String pesquisa = txtPesquisa.getText().trim();
        
        if(pesquisa.isEmpty()){
            JOptionPane.showMessageDialog(this, "Digite a pasquisa ou parte dela", "Pesquisa vazia", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        DefaultTableModel modelo = (DefaultTableModel) tblConsultaOrdem.getModel();
        
        modelo.setRowCount(0);
        
        String tipo_pesquisa = cmbPesquisePor.getSelectedItem().toString();
        
        String sql = "";
        
        if(tipo_pesquisa == "Numero da OS"){
            sql = "SELECT * FROM ordem_servico WHERE nome ILIKE ? ORDER BY numeroDaOS";
        }
        if(tipo_pesquisa == "Placa"){
            sql = "SELECT * FROM ordem_servico WHERE cpf ILIKE ? ORDER BY placa";
        }
        if(tipo_pesquisa == "Cliente"){
            sql = "SELECT * FROM ordem_servico WHERE id = ? ORDER BY cliente";
        }
         if(tipo_pesquisa == "Mecanico"){
            sql = "SELECT * FROM ordem_servico WHERE id = ? ORDER BY mecanico";
        }
          if(tipo_pesquisa == "Servico"){
            sql = "SELECT * FROM ordem_servico WHERE id = ? ORDER BY servico";
        }
         if(tipo_pesquisa == "dataAbertura"){
            sql = "SELECT * FROM ordem_servico WHERE id = ? ORDER BY dataAbertura";
        }
         if(tipo_pesquisa == "Status"){
            sql = "SELECT * FROM ordem_servico WHERE id = ? ORDER BY Status";
        }
         if(tipo_pesquisa == "valorCobrado"){
            sql = "SELECT * FROM ordem_servico WHERE id = ? ORDER BY valorCobrado";
        }
         if(tipo_pesquisa == "dataConclusao"){
            sql = "SELECT * FROM ordem_servico WHERE id = ? ORDER BY dataConclusao";
        }
         
         
        try (Connection conex = Conexao.conectar();
             PreparedStatement stmt = conex.prepareStatement(sql)){
            
            
            if(tipo_pesquisa.equals("numeroDaOS")){
                stmt.setInt(1, Integer.parseInt(pesquisa));
            }else{
                stmt.setString(1, "%" + pesquisa + "%");
            }
            
            try (ResultSet resultado = stmt.executeQuery()){
                while (resultado.next()){
                    modelo.addRow(new Object [] {
                        resultado.getInt("numero da OS"),
                        resultado.getString("placa"),
                        resultado.getString("cliente"),
                        resultado.getString("mecanico"),
                        resultado.getString("servico"),
                        resultado.getString("dataAbertura"),
                        resultado.getString("status"),
                        resultado.getString("valorCobrado"),
                        resultado.getString("dataConclusao"),
                        resultado.getBoolean("ativo")
                    });
                }
            }
            
            if(modelo.getRowCount() == 0){
                JOptionPane.showMessageDialog(this, "Nenhuma ordem de servico encontrada para: " + pesquisa, "Resultado da Pesquisa", JOptionPane.INFORMATION_MESSAGE);
            }
        } catch (SQLException erro){
            JOptionPane.showMessageDialog(this,
                "Erro ao localizar ordem de servico:\n" + erro.getMessage(),
                "Erro no banco de dados",
                JOptionPane.ERROR_MESSAGE);
        } 
    }//GEN-LAST:event_btnLocalizarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = tblConsultaOrdem.getSelectedRow();
        
        if(linha == -1){
           JOptionPane.showMessageDialog(this,"Selecione um mecanico para excluir!");
           return; 
        }
        
        int id = Integer.parseInt(tblConsultaOrdem.getValueAt(linha, 0).toString());
        
        int resposta = JOptionPane.showConfirmDialog(this, 
            "Deseja realmente excluir ordem de serviço do ID "+ id + " ?",
            "Confirmar Exclusão",
            JOptionPane.YES_NO_CANCEL_OPTION,
            JOptionPane.QUESTION_MESSAGE);
        
        if (resposta != JOptionPane.YES_OPTION) {
            return;
        }
        
        String sql = "DELETE FROM ordem_servico WHERE id = ?";
        
        try (Connection conex = Conexao.conectar();
                PreparedStatement stmt = conex.prepareStatement(sql)){
            
            stmt.setInt(1, id);
            
            int registros = stmt.executeUpdate();
            if (registros > 0){
                JOptionPane.showMessageDialog(this, "Ordem de servico excluido com sucesso!");
                atualizarTabela();
            } else {
                JOptionPane.showMessageDialog(this, "Ordem de servico não encontrado!");
            }
        } catch (SQLException erro){
            JOptionPane.showMessageDialog(this, "Erro ao excluir Ordem de servico: " + erro.getMessage());
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

