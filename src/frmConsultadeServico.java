    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        int linha = tblConsultaServico.getSelectedRow();
         
        if (linha == -1){
            JOptionPane.showMessageDialog(this,"Selecione um servico na tabela para alterar");
            return;
        }
         
         
        int id = Integer.parseInt(tblConsultaServico.getValueAt(linha,0).toString());
         
         
        int Id = Integer.parseInt(txtId.getText().trim());
        String categoria = txtCategoria.getText().trim();
        float valorBase = Float.parseFloat(txtValorBase.getText().trim());
        float tempoEstimado = Float.parseFloat(txtTempoEstimado.getText().trim());
        String descricao = txtDescricao.getText().trim();
         
        
        if (categoria.isEmpty() || descricao.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Preecha os campos OBRIGATÓRIOS: Id, Categoria, valor_base, Tempo_estimado_horas, Descricao");
            return;
        }
         
        
         
         int resposta = JOptionPane.showConfirmDialog(this, 
                         "Deseja alterar os dados do servico de ID "+id+"?" ,
                         "Confirmar Alteração",
                         JOptionPane.YES_NO_CANCEL_OPTION,
                         JOptionPane.QUESTION_MESSAGE);
         if (resposta != JOptionPane.YES_OPTION) {
             return;
         }
         
        
         
         String sql = """
             UPDATE servico
             SET categoria = ?, valor_base = ?, tempo_estimado_horas = ?, descricao = ?, ativo = ?
             WHERE id = ?
             """;
         
         try (Connection conex = Conexao.conectar();
              PreparedStatement stmt = conex.prepareStatement(sql)){
           
             stmt.setString(1, categoria);
    stmt.setFloat(2, valorBase);
    stmt.setFloat(3, tempoEstimado);
    stmt.setString(4, descricao);
    stmt.setBoolean(5, chbAtivo.isSelected());
    stmt.setInt(6, Id);
             
            
             int registros = stmt.executeUpdate();
             if (registros > 0){
                 JOptionPane.showMessageDialog(this, "servico alterado com sucesso!");
                 atualizarTabela();
                 txtId.setText("");
                 txtCategoria.setText("");
                 txtValorBase.setText("");
                 txtTempoEstimado.setText("");
                 txtDescricao.setText("");
                 chbAtivo.setSelected(false);
                 txtCategoria.requestFocus();
             } else {
                 JOptionPane.showMessageDialog(this, "Servico não encontrado");
             }
         } catch (SQLException erro){
           JOptionPane.showMessageDialog(this, "Erro ao alterar Servico: " + erro.getMessage());
         }
    }//GEN-LAST:event_btnAlterarActionPerformed

